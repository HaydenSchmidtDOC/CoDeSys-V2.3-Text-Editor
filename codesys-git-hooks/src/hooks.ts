/**
 * Git hook implementations.
 *
 * These functions are called by the actual git hooks in githooks/ and handle
 * the projection sync workflow.
 */

import * as fs from "fs";
import * as path from "path";
import { execSync } from "child_process";
import { exportProjection, detectDrift, importProjection } from "./projection";

/**
 * pre-commit hook: for each staged .pro file, detect drift, then export.
 *
 * 1. Get the list of staged .pro files
 * 2. For each one, run drift detection (compare working tree .pro.src/ against HEAD)
 * 3. If drift detected, abort with error message
 * 4. If clean, parse() and export() to regenerate .pro.src/
 * 5. Stage the .pro.src/ directory
 */
export function preCommitHook(repoRoot: string): void {
  try {
    // Get staged files via git
    const stagedOutput = execSync("git diff --cached --name-only -z", {
      cwd: repoRoot,
      encoding: "utf8",
    });

    const stagedFiles = stagedOutput
      .split("\0")
      .filter((f) => f.endsWith(".pro"));

    if (stagedFiles.length === 0) {
      // No .pro files staged, nothing to do
      process.exit(0);
    }

    let hadError = false;

    for (const proFile of stagedFiles) {
      const proPath = path.join(repoRoot, proFile);
      const headProPath = proPath; // For drift detection, use the current working .pro

      try {
        // Drift detection: compare working tree .pro.src/ against what HEAD's .pro would produce
        // We need to check out HEAD version temporarily for drift detection
        let headContent: Buffer;
        try {
          const headOutput = execSync(`git show HEAD:${proFile}`, {
            cwd: repoRoot,
            encoding: "buffer",
          });
          headContent = headOutput as Buffer;
        } catch {
          // File doesn't exist in HEAD (new file), no drift check needed
          console.log(`[codesys-git-hooks] ${proFile}: new file, skipping drift check`);
          exportProjection(proPath);
          continue;
        }

        // Write HEAD version to a temp file for drift detection
        const tempHeadPath = proPath + ".HEAD";
        fs.writeFileSync(tempHeadPath, headContent);

        try {
          const drift = detectDrift(proPath, tempHeadPath);
          if (drift.drift) {
            console.error(
              `[codesys-git-hooks] ${proFile}.src/: DRIFT DETECTED - the following files were hand-edited (they should only be generated by git hooks):`
            );
            for (const file of drift.driftedFiles) {
              console.error(`  ${file}`);
            }
            console.error(
              `\nEdit ${proFile} directly instead. The projection will be regenerated automatically.`
            );
            hadError = true;
            continue;
          }

          // No drift, safe to regenerate
          console.log(`[codesys-git-hooks] ${proFile}: regenerating projection...`);
          exportProjection(proPath);

          // Stage the .pro.src/ directory
          const projDir = proPath + ".src";
          execSync(`git add "${projDir}"`, { cwd: repoRoot });
          console.log(`[codesys-git-hooks] ${proFile}.src/: staged for commit`);
        } finally {
          fs.unlinkSync(tempHeadPath);
        }
      } catch (err) {
        console.error(
          `[codesys-git-hooks] ${proFile}: error during pre-commit - ${(err as Error).message}`
        );
        hadError = true;
      }
    }

    if (hadError) {
      process.exit(1);
    }
  } catch (err) {
    console.error(`[codesys-git-hooks] pre-commit hook failed: ${(err as Error).message}`);
    process.exit(1);
  }
}

/**
 * post-checkout hook: for each .pro whose .pro.src/ changed, import and rebuild.
 *
 * Runs after checkout, merge-base update, or branch switch.
 * Re-materializes the .pro from the committed projection.
 */
export function postCheckoutHook(repoRoot: string): void {
  try {
    // Get all .pro.src directories that exist in the current HEAD
    const walkDir = (dir: string) => {
      const files: string[] = [];
      if (!fs.existsSync(dir)) return files;

      for (const file of fs.readdirSync(dir)) {
        if (file.endsWith(".pro.src")) {
          files.push(path.join(dir, file));
        } else {
          const fullPath = path.join(dir, file);
          const stat = fs.statSync(fullPath);
          if (stat.isDirectory()) {
            files.push(...walkDir(fullPath));
          }
        }
      }
      return files;
    };

    const projDirs = walkDir(repoRoot);

    for (const projDir of projDirs) {
      try {
        console.log(`[codesys-git-hooks] Importing ${projDir}...`);
        const newBuf = importProjection(projDir);

        const proPath = projDir.endsWith(".src")
          ? projDir.slice(0, -4)
          : projDir + ".pro";
        fs.writeFileSync(proPath, newBuf);
        console.log(`[codesys-git-hooks] ${proPath}: rebuilt from projection`);
      } catch (err) {
        console.error(
          `[codesys-git-hooks] Error importing ${projDir}: ${(err as Error).message}`
        );
        // Continue with other files rather than failing the checkout
      }
    }
  } catch (err) {
    console.error(`[codesys-git-hooks] post-checkout hook failed: ${(err as Error).message}`);
    // Don't exit(1) on post-* hooks - they should be best-effort
  }
}

/**
 * post-merge hook: same as post-checkout.
 */
export function postMergeHook(repoRoot: string): void {
  postCheckoutHook(repoRoot);
}

/**
 * post-rewrite hook: same as post-checkout, called after rebase/amend.
 */
export function postRewriteHook(repoRoot: string): void {
  postCheckoutHook(repoRoot);
}
